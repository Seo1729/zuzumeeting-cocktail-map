import { Hono } from 'hono'
import { listPosts } from '../store.ts'

/*
  게시글 라우트.

  이 파일이 하는 일은 딱 셋이다.
    1. HTTP 요청에서 필요한 값을 꺼낸다 (URL 파라미터, 본문)
    2. 저장소 함수를 부른다
    3. 결과를 상태 코드와 함께 JSON으로 돌려준다

  비즈니스 로직을 여기 넣지 않는다. 그건 store.ts의 일이다.
*/

export const posts = new Hono()

/*
  GET /posts — 목록

  이 라우트 하나가 완성된 예제다. 나머지 TODO는 이 모양을 따라 만들면 된다.
  200은 Hono가 기본으로 붙여주지만, 상태 코드를 의식하는 습관을 들이려고 명시했다.
*/
posts.get('/', (c) => {
  return c.json(listPosts(), 200)
})

